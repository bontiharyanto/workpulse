import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { Cron } from '@nestjs/schedule';

import { TimesheetSchedulerService } from './timesheet-scheduler.service';

/**
 * Fase 32f — daily cron for timesheet auto-generation + reminders.
 *
 * Cadence: once per day at **03:00 UTC** — matches RetentionWorker and
 * DataExportWorker.retentionSweep. In Asia/Jakarta (UTC+7) that's
 * 10:00 local, which lands during the local workday for our primary
 * tenant region. Multi-region customers can request per-tenant
 * dispatch hours in a follow-up phase.
 *
 * Idempotency: auto-generation upserts on
 * `(companyId, periodStart, periodEnd)`, reminders are gated by the
 * unique index on `TimesheetReminderLog(timesheetId, type, sentDate)`.
 * Re-running this cron in the same UTC day is a no-op.
 */
@Injectable()
export class TimesheetSchedulerWorker {
  private readonly logger = new Logger(TimesheetSchedulerWorker.name);
  private tickRunning = false;
  private readonly enabled: boolean;

  constructor(
    private readonly service: TimesheetSchedulerService,
    config: ConfigService,
  ) {
    this.enabled = config.get<string>('TIMESHEET_SCHEDULER_ENABLED', 'true') !== 'false';
    if (!this.enabled) {
      this.logger.warn(
        'TIMESHEET_SCHEDULER_ENABLED=false — timesheet auto-gen + reminders disabled on this instance.',
      );
    }
  }

  @Cron('0 0 3 * * *', { name: 'timesheet-scheduler-tick' })
  async tick(): Promise<void> {
    if (!this.enabled || this.tickRunning) return;
    this.tickRunning = true;
    const started = Date.now();
    try {
      const reports = await this.service.sweepAllTenants(new Date());
      const fired = reports.filter(
        (r) => r.autoGenerated || r.submitRemindersSent > 0 || r.approvalRemindersSent > 0,
      );
      this.logger.log(
        `scheduler tick complete tenants=${reports.length} fired=${
          fired.length
        } durationMs=${Date.now() - started}`,
      );
    } catch (err) {
      this.logger.error(`scheduler tick crashed: ${(err as Error).message}`);
    } finally {
      this.tickRunning = false;
    }
  }

  /**
   * Test-only entry point (`POST /test-support/timesheet-scheduler/tick`).
   * Sweeps all tenants synchronously and returns the reports so E2E can
   * assert side effects.
   */
  async tickForTest(
    now: Date = new Date(),
  ): Promise<Awaited<ReturnType<TimesheetSchedulerService['sweepAllTenants']>>> {
    return this.service.sweepAllTenants(now);
  }
}
