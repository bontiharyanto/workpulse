import { Injectable, Logger } from '@nestjs/common';
import type { Prisma } from '@prisma/client';

import {
  timesheetApprovalReminder,
  timesheetSubmitReminder,
} from '../notification/domain/templates';
import { NotificationService } from '../notification/notification.service';
import { PrismaService } from '../prisma/prisma.service';
import {
  decideApprovalReminder,
  decideAutoGenerate,
  decideSubmitReminder,
  daysBetweenYmd,
  todayInTz,
} from './domain/scheduler-decision';
import { TimesheetService } from './timesheet.service';

export interface SweepReport {
  companyId: string;
  autoGenerated: boolean;
  submitRemindersSent: number;
  approvalRemindersSent: number;
  skipped: boolean;
  reason?: string;
}

const RECENT_PERIOD_LOOKBACK_DAYS = 60;

/**
 * Fase 32f — per-tenant scheduler logic.
 *
 * The worker owns the cron; this service owns the "what to do for ONE
 * tenant" step so it can be exercised in-process by test-support and
 * unit tests. Every branch is decided upstream in
 * `domain/scheduler-decision.ts` so the service itself is pure IO.
 *
 * Idempotency:
 *   * Auto-generation reuses `TimesheetService.generateForPeriod`
 *     which upserts on `(companyId, periodStart, periodEnd)`. Firing
 *     twice a day is a no-op.
 *   * Reminders are gated by the unique index on
 *     `TimesheetReminderLog(timesheetId, type, sentDate)`. A P2002
 *     from a concurrent worker silently skips the notification
 *     creation for that timesheet.
 */
@Injectable()
export class TimesheetSchedulerService {
  private readonly logger = new Logger(TimesheetSchedulerService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly timesheetService: TimesheetService,
    private readonly notifications: NotificationService,
  ) {}

  /**
   * Iterate every company that has a `TimesheetConfig`. Called by the
   * worker at each tick; safe to call synchronously from test-support.
   */
  async sweepAllTenants(now: Date = new Date()): Promise<SweepReport[]> {
    const tenants = await this.prisma.timesheetConfig.findMany({
      select: { companyId: true },
    });
    const reports: SweepReport[] = [];
    for (const t of tenants) {
      try {
        reports.push(await this.sweepOneTenant(t.companyId, now));
      } catch (err) {
        this.logger.error(
          `scheduler sweep crashed for company=${t.companyId}: ${(err as Error).message}`,
        );
        reports.push({
          companyId: t.companyId,
          autoGenerated: false,
          submitRemindersSent: 0,
          approvalRemindersSent: 0,
          skipped: true,
          reason: 'ERROR',
        });
      }
    }
    return reports;
  }

  async sweepOneTenant(companyId: string, now: Date = new Date()): Promise<SweepReport> {
    const config = await this.prisma.timesheetConfig.findUnique({
      where: { companyId },
    });
    if (!config) {
      return this.skipped(companyId, 'NO_CONFIG');
    }
    const todayYmd = todayInTz(now, config.timezone);

    // ---- 1. Auto-generation ---------------------------------------------
    const latestPeriod = await this.prisma.timesheetPeriod.findFirst({
      where: { companyId },
      orderBy: { periodEnd: 'desc' },
      select: { periodEnd: true, periodStart: true },
    });
    const latestPeriodEndYmd = latestPeriod ? formatDbDateYmd(latestPeriod.periodEnd) : null;
    const autoDecision = decideAutoGenerate({
      autoGenerateEnabled: config.autoGenerateEnabled,
      latestPeriodEndYmd,
      todayYmd,
    });
    let autoGenerated = false;
    if (autoDecision.fire) {
      await this.timesheetService.generateForPeriod(companyId, now);
      autoGenerated = true;
      this.logger.log(
        `auto-generated timesheets: company=${companyId} reason=${autoDecision.reason}`,
      );
    }

    // ---- 2. Reminders ---------------------------------------------------
    let submitRemindersSent = 0;
    let approvalRemindersSent = 0;
    if (config.reminderEnabled) {
      // Look at every timesheet in a period whose end is within the
      // lookback window. The window is bounded to keep the query cheap;
      // reminders past `submit/approvalReminderMaxDays` are refused by
      // the decision function anyway.
      const cutoffDate = subtractDaysYmd(todayYmd, RECENT_PERIOD_LOOKBACK_DAYS);
      const cutoffPeriodEnd = dbDateFromYmd(cutoffDate);
      const timesheets = await this.prisma.timesheet.findMany({
        where: {
          companyId,
          status: {
            in: ['DRAFT', 'REJECTED', 'PENDING_SUPERVISOR', 'PENDING_HR'],
          },
          period: {
            periodEnd: { gte: cutoffPeriodEnd },
          },
        },
        include: {
          user: {
            select: {
              id: true,
              email: true,
              fullName: true,
              supervisorId: true,
              role: true,
            },
          },
          period: {
            select: {
              id: true,
              label: true,
              periodStart: true,
              periodEnd: true,
            },
          },
        },
      });

      // Cache the tenant's HR + Super Admin roster so we only hit the
      // DB once per sweep. Approval reminders for PENDING_HR fan out
      // to every HR user; the actor id on the timesheet only exists
      // AFTER a decision has been recorded.
      const hrRecipients = await this.prisma.user.findMany({
        where: {
          companyId,
          deletedAt: null,
          role: { in: ['HR_MANAGER', 'SUPER_ADMIN'] },
        },
        select: {
          id: true,
          email: true,
          fullName: true,
        },
      });

      for (const ts of timesheets) {
        const periodEndYmd = formatDbDateYmd(ts.period.periodEnd);
        const daysOverdue = Math.max(0, daysBetweenYmd(periodEndYmd, todayYmd));

        // Submit reminder — recipient is the user themselves.
        const submitDecision = decideSubmitReminder({
          reminderEnabled: config.reminderEnabled,
          submitReminderStartDays: config.submitReminderStartDays,
          submitReminderMaxDays: config.submitReminderMaxDays,
          periodEndYmd,
          todayYmd,
          timesheetStatus: ts.status,
        });
        if (submitDecision.fire) {
          const sent = await this.tryLogAndNotify({
            timesheetId: ts.id,
            companyId,
            type: 'TIMESHEET_SUBMIT_REMINDER',
            recipient: {
              id: ts.user.id,
              email: ts.user.email,
              fullName: ts.user.fullName,
            },
            todayYmd,
            content: timesheetSubmitReminder({
              timesheetId: ts.id,
              periodLabel: ts.period.label,
              periodStart: formatDbDateYmd(ts.period.periodStart),
              periodEnd: periodEndYmd,
              daysOverdue,
            }),
          });
          if (sent) submitRemindersSent += 1;
        }

        // Approval reminder — recipient(s) depend on the stage.
        const approvalDecision = decideApprovalReminder({
          reminderEnabled: config.reminderEnabled,
          approvalReminderStartDays: config.approvalReminderStartDays,
          approvalReminderMaxDays: config.approvalReminderMaxDays,
          periodEndYmd,
          todayYmd,
          timesheetStatus: ts.status,
        });
        if (approvalDecision.fire) {
          const recipients =
            approvalDecision.targetQueue === 'SUPERVISOR'
              ? await this.supervisorRecipient(ts.user.supervisorId)
              : hrRecipients;
          for (const r of recipients) {
            const sent = await this.tryLogAndNotify({
              timesheetId: ts.id,
              companyId,
              type: 'TIMESHEET_APPROVAL_REMINDER',
              recipient: r,
              todayYmd,
              content: timesheetApprovalReminder({
                timesheetId: ts.id,
                periodLabel: ts.period.label,
                periodStart: formatDbDateYmd(ts.period.periodStart),
                periodEnd: periodEndYmd,
                daysOverdue,
                requesterName: ts.user.fullName,
                queue: approvalDecision.targetQueue,
              }),
            });
            if (sent) approvalRemindersSent += 1;
          }
        }
      }
    }

    return {
      companyId,
      autoGenerated,
      submitRemindersSent,
      approvalRemindersSent,
      skipped: false,
    };
  }

  /**
   * Insert the reminder-log row + notification atomically. The unique
   * index on (timesheetId, type, sentDate) is the concurrency gate —
   * a second worker on another replica will hit P2002 and we return
   * `false` so caller counters stay accurate.
   */
  private async tryLogAndNotify(input: {
    timesheetId: string;
    companyId: string;
    type: 'TIMESHEET_SUBMIT_REMINDER' | 'TIMESHEET_APPROVAL_REMINDER';
    recipient: { id: string; email: string; fullName: string };
    todayYmd: string;
    content: ReturnType<typeof timesheetSubmitReminder>;
  }): Promise<boolean> {
    try {
      await this.prisma.$transaction(async (tx) => {
        await tx.timesheetReminderLog.create({
          data: {
            timesheetId: input.timesheetId,
            companyId: input.companyId,
            type: input.type,
            recipientId: input.recipient.id,
            sentDate: dbDateFromYmd(input.todayYmd),
          },
        });
        await this.notifications.createOne(
          {
            companyId: input.companyId,
            recipientId: input.recipient.id,
            recipientEmail: input.recipient.email,
            content: input.content,
          },
          tx as unknown as Prisma.TransactionClient,
        );
      });
      return true;
    } catch (err) {
      if ((err as { code?: string }).code === 'P2002') {
        // Concurrent worker already fired this reminder today.
        return false;
      }
      this.logger.warn(
        `reminder emit failed: timesheet=${input.timesheetId} recipient=${input.recipient.id} err=${(err as Error).message}`,
      );
      return false;
    }
  }

  private async supervisorRecipient(
    supervisorId: string | null,
  ): Promise<Array<{ id: string; email: string; fullName: string }>> {
    if (!supervisorId) return [];
    const supervisor = await this.prisma.user.findFirst({
      where: { id: supervisorId, deletedAt: null },
      select: { id: true, email: true, fullName: true },
    });
    return supervisor ? [supervisor] : [];
  }

  private skipped(companyId: string, reason: string): SweepReport {
    return {
      companyId,
      autoGenerated: false,
      submitRemindersSent: 0,
      approvalRemindersSent: 0,
      skipped: true,
      reason,
    };
  }
}

// ---------------------------------------------------------------------------
// Local date helpers — keep the scheduler pure of UTC-vs-local drift.
// ---------------------------------------------------------------------------

/**
 * Prisma returns `@db.Date` values as `Date` at UTC midnight. Convert
 * back to YYYY-MM-DD without shifting to the caller's local TZ.
 */
function formatDbDateYmd(d: Date): string {
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}-${String(d.getUTCDate()).padStart(2, '0')}`;
}

function dbDateFromYmd(ymd: string): Date {
  return new Date(`${ymd}T00:00:00.000Z`);
}

function subtractDaysYmd(ymd: string, days: number): string {
  const base = new Date(`${ymd}T00:00:00.000Z`);
  base.setUTCDate(base.getUTCDate() - days);
  return `${base.getUTCFullYear()}-${String(base.getUTCMonth() + 1).padStart(2, '0')}-${String(base.getUTCDate()).padStart(2, '0')}`;
}

