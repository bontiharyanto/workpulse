import type { TimesheetConfig, TimesheetPeriod } from '@prisma/client';
import type { DeepMockProxy } from 'jest-mock-extended';
import { mockDeep, mockReset } from 'jest-mock-extended';

import { TimesheetSchedulerService } from './timesheet-scheduler.service';
import { TimesheetService } from './timesheet.service';
import { NotificationService } from '../notification/notification.service';
import { PrismaService } from '../prisma/prisma.service';

interface Kit {
  service: TimesheetSchedulerService;
  prisma: DeepMockProxy<PrismaService>;
  timesheetService: DeepMockProxy<TimesheetService>;
  notifications: DeepMockProxy<NotificationService>;
}

function buildKit(): Kit {
  const prisma = mockDeep<PrismaService>();
  const timesheetService = mockDeep<TimesheetService>();
  const notifications = mockDeep<NotificationService>();
  mockReset(prisma);
  mockReset(timesheetService);
  mockReset(notifications);

  // $transaction — invoke the callback with the same mocked handle so
  // every call inside the tx routes back to our stubs.
  (prisma.$transaction as unknown as jest.Mock).mockImplementation(async (arg: unknown) => {
    if (typeof arg === 'function') {
      return (arg as (tx: PrismaService) => unknown)(prisma);
    }
    return Promise.all(arg as Promise<unknown>[]);
  });

  notifications.createOne.mockResolvedValue(undefined as never);

  const service = new TimesheetSchedulerService(
    prisma as unknown as PrismaService,
    timesheetService as unknown as TimesheetService,
    notifications as unknown as NotificationService,
  );

  return { service, prisma, timesheetService, notifications };
}

function makeConfig(overrides: Partial<TimesheetConfig> = {}): TimesheetConfig {
  return {
    id: 'cfg-1',
    companyId: 'c-1',
    periodType: 'MONTHLY',
    weekStartDay: 'MONDAY',
    biweeklyAnchor: null,
    cutoffDayOfMonth: null,
    timezone: 'Asia/Jakarta',
    autoGenerateEnabled: true,
    reminderEnabled: true,
    submitReminderStartDays: 1,
    submitReminderMaxDays: 7,
    approvalReminderStartDays: 2,
    approvalReminderMaxDays: 14,
    createdAt: new Date(),
    updatedAt: new Date(),
    updatedById: null,
    ...overrides,
  } as TimesheetConfig;
}

function makePeriod(overrides: Partial<TimesheetPeriod> = {}): TimesheetPeriod {
  return {
    id: 'p-1',
    companyId: 'c-1',
    periodType: 'MONTHLY',
    periodStart: new Date('2026-07-01T00:00:00Z'),
    periodEnd: new Date('2026-07-31T00:00:00Z'),
    label: 'Jul 2026',
    generatedAt: new Date(),
    ...overrides,
  } as TimesheetPeriod;
}

describe('TimesheetSchedulerService', () => {
  it('skips tenants with no TimesheetConfig row', async () => {
    const kit = buildKit();
    kit.prisma.timesheetConfig.findUnique.mockResolvedValue(null as never);

    const rep = await kit.service.sweepOneTenant('c-nope');
    expect(rep.skipped).toBe(true);
    expect(rep.reason).toBe('NO_CONFIG');
    expect(kit.timesheetService.generateForPeriod).not.toHaveBeenCalled();
  });

  it('fires auto-generation when today is after the latest periodEnd', async () => {
    const kit = buildKit();
    kit.prisma.timesheetConfig.findUnique.mockResolvedValue(makeConfig() as never);
    kit.prisma.timesheetPeriod.findFirst.mockResolvedValue(makePeriod() as never);
    kit.prisma.timesheet.findMany.mockResolvedValue([] as never);
    kit.prisma.user.findMany.mockResolvedValue([] as never);
    kit.timesheetService.generateForPeriod.mockResolvedValue({
      periodId: 'p-2',
      timesheetsGenerated: 3,
      timesheetsSkippedApproved: 0,
    } as never);

    const rep = await kit.service.sweepOneTenant('c-1', new Date('2026-08-05T00:00:00Z'));
    expect(rep.autoGenerated).toBe(true);
    expect(kit.timesheetService.generateForPeriod).toHaveBeenCalledTimes(1);
  });

  it('sends a submit reminder for a DRAFT timesheet past the start window', async () => {
    const kit = buildKit();
    kit.prisma.timesheetConfig.findUnique.mockResolvedValue(
      makeConfig({ autoGenerateEnabled: false }) as never, // isolate the reminder branch
    );
    kit.prisma.timesheetPeriod.findFirst.mockResolvedValue(makePeriod() as never);
    kit.prisma.user.findMany.mockResolvedValue([] as never);
    kit.prisma.timesheet.findMany.mockResolvedValue([
      {
        id: 'ts-1',
        companyId: 'c-1',
        status: 'DRAFT',
        user: {
          id: 'u-1',
          email: 'employee@example.com',
          fullName: 'Employee',
          supervisorId: null,
          role: 'EMPLOYEE',
        },
        period: {
          id: 'p-1',
          label: 'Jul 2026',
          periodStart: new Date('2026-07-01T00:00:00Z'),
          periodEnd: new Date('2026-07-31T00:00:00Z'),
        },
      },
    ] as never);
    kit.prisma.timesheetReminderLog.create.mockResolvedValue({} as never);

    const rep = await kit.service.sweepOneTenant('c-1', new Date('2026-08-03T00:00:00Z'));
    expect(rep.submitRemindersSent).toBe(1);
    expect(kit.notifications.createOne).toHaveBeenCalledTimes(1);
    expect(kit.notifications.createOne.mock.calls[0]?.[0].content.type).toBe(
      'TIMESHEET_SUBMIT_REMINDER',
    );
  });

  it('sends an approval reminder to HR users for a PENDING_HR timesheet', async () => {
    const kit = buildKit();
    kit.prisma.timesheetConfig.findUnique.mockResolvedValue(
      makeConfig({ autoGenerateEnabled: false }) as never,
    );
    kit.prisma.timesheetPeriod.findFirst.mockResolvedValue(makePeriod() as never);
    kit.prisma.timesheet.findMany.mockResolvedValue([
      {
        id: 'ts-hr-1',
        companyId: 'c-1',
        status: 'PENDING_HR',
        user: {
          id: 'u-1',
          email: 'employee@example.com',
          fullName: 'Employee One',
          supervisorId: 'sup-1',
          role: 'EMPLOYEE',
        },
        period: {
          id: 'p-1',
          label: 'Jul 2026',
          periodStart: new Date('2026-07-01T00:00:00Z'),
          periodEnd: new Date('2026-07-31T00:00:00Z'),
        },
      },
    ] as never);
    kit.prisma.user.findMany.mockResolvedValue([
      { id: 'hr-1', email: 'hr1@example.com', fullName: 'HR One' },
      { id: 'hr-2', email: 'hr2@example.com', fullName: 'HR Two' },
    ] as never);
    kit.prisma.timesheetReminderLog.create.mockResolvedValue({} as never);

    const rep = await kit.service.sweepOneTenant('c-1', new Date('2026-08-05T00:00:00Z'));
    expect(rep.approvalRemindersSent).toBe(2);
    const types = kit.notifications.createOne.mock.calls.map(
      (c) => (c[0] as { content: { type: string } }).content.type,
    );
    expect(types).toEqual(['TIMESHEET_APPROVAL_REMINDER', 'TIMESHEET_APPROVAL_REMINDER']);
  });

  it('respects reminderEnabled = false as a master switch', async () => {
    const kit = buildKit();
    kit.prisma.timesheetConfig.findUnique.mockResolvedValue(
      makeConfig({ autoGenerateEnabled: false, reminderEnabled: false }) as never,
    );
    kit.prisma.timesheetPeriod.findFirst.mockResolvedValue(makePeriod() as never);

    const rep = await kit.service.sweepOneTenant('c-1');
    expect(rep.submitRemindersSent).toBe(0);
    expect(rep.approvalRemindersSent).toBe(0);
    expect(kit.notifications.createOne).not.toHaveBeenCalled();
    // We also should not even query for timesheets when reminders off.
    expect(kit.prisma.timesheet.findMany).not.toHaveBeenCalled();
  });

  it('treats P2002 from the reminder log as a silent dedupe, not a counted fire', async () => {
    const kit = buildKit();
    kit.prisma.timesheetConfig.findUnique.mockResolvedValue(
      makeConfig({ autoGenerateEnabled: false }) as never,
    );
    kit.prisma.timesheetPeriod.findFirst.mockResolvedValue(makePeriod() as never);
    kit.prisma.timesheet.findMany.mockResolvedValue([
      {
        id: 'ts-1',
        companyId: 'c-1',
        status: 'DRAFT',
        user: {
          id: 'u-1',
          email: 'employee@example.com',
          fullName: 'Employee',
          supervisorId: null,
          role: 'EMPLOYEE',
        },
        period: {
          id: 'p-1',
          label: 'Jul 2026',
          periodStart: new Date('2026-07-01T00:00:00Z'),
          periodEnd: new Date('2026-07-31T00:00:00Z'),
        },
      },
    ] as never);
    kit.prisma.user.findMany.mockResolvedValue([] as never);
    (kit.prisma.timesheetReminderLog.create as unknown as jest.Mock).mockImplementation(() => {
      const err = new Error('duplicate') as Error & { code?: string };
      err.code = 'P2002';
      return Promise.reject(err);
    });

    const rep = await kit.service.sweepOneTenant('c-1', new Date('2026-08-03T00:00:00Z'));
    expect(rep.submitRemindersSent).toBe(0);
    expect(kit.notifications.createOne).not.toHaveBeenCalled();
  });
});
