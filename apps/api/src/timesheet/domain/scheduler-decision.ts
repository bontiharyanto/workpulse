import type { TimesheetStatus } from '@prisma/client';

/**
 * Fase 32f — pure decision functions used by the scheduler worker.
 *
 * Kept free of Prisma / Nest so each branch is unit-testable against
 * plain-object fixtures. The worker owns all IO; this module owns the
 * "what SHOULD happen given these facts?" question.
 *
 * Timezone contract
 * -----------------
 * All dates in this module are `Date` objects in the tenant's
 * timezone-agnostic UTC representation, but the *calendar day* they
 * describe is the tenant's local day. Callers project both sides of
 * a comparison to the tenant TZ before invoking us (see
 * `todayInTz` / `daysBetweenLocal`).
 */

/** Simple TZ-aware Y-M-D projection. Reused by the worker. */
export function todayInTz(now: Date, timezone: string): string {
  const dtf = new Intl.DateTimeFormat('en-CA', {
    timeZone: timezone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  });
  return dtf.format(now); // 'YYYY-MM-DD'
}

/**
 * Whole-day count from `earlier` to `later`, both YYYY-MM-DD strings.
 * Positive when `later > earlier`. Deliberately ignores hours to sidestep
 * DST edge cases — the scheduler only cares about calendar-day
 * granularity.
 */
export function daysBetweenYmd(earlier: string, later: string): number {
  const a = Date.UTC(
    Number(earlier.slice(0, 4)),
    Number(earlier.slice(5, 7)) - 1,
    Number(earlier.slice(8, 10)),
  );
  const b = Date.UTC(
    Number(later.slice(0, 4)),
    Number(later.slice(5, 7)) - 1,
    Number(later.slice(8, 10)),
  );
  return Math.round((b - a) / 86_400_000);
}

// ---------------------------------------------------------------------------
// Auto-generation
// ---------------------------------------------------------------------------

export interface AutoGenerateFacts {
  autoGenerateEnabled: boolean;
  /** Latest existing period for this tenant, or null if none exists. */
  latestPeriodEndYmd: string | null;
  /** Today in tenant TZ (Y-M-D). */
  todayYmd: string;
}

export type AutoGenerateDecision =
  | { fire: false; reason: 'DISABLED' | 'NOT_YET_DUE' }
  | { fire: true; reason: 'INITIAL' | 'NEXT_PERIOD' };

/**
 * Decide whether to run `generateForPeriod(today)` for this tenant.
 *
 * Rules:
 *   - If `autoGenerateEnabled` is off → skip.
 *   - If there's no period yet → INITIAL fire (bootstrap the first period).
 *   - If today falls INSIDE the latest known period → skip (already covered).
 *   - If today is AFTER the latest period ended → fire so the next
 *     period is created lazily. Idempotent because generateForPeriod
 *     upserts on `(companyId, periodStart, periodEnd)`.
 */
export function decideAutoGenerate(facts: AutoGenerateFacts): AutoGenerateDecision {
  if (!facts.autoGenerateEnabled) {
    return { fire: false, reason: 'DISABLED' };
  }
  if (facts.latestPeriodEndYmd === null) {
    return { fire: true, reason: 'INITIAL' };
  }
  const gap = daysBetweenYmd(facts.latestPeriodEndYmd, facts.todayYmd);
  if (gap <= 0) return { fire: false, reason: 'NOT_YET_DUE' };
  return { fire: true, reason: 'NEXT_PERIOD' };
}

// ---------------------------------------------------------------------------
// Submit reminder
// ---------------------------------------------------------------------------

export interface SubmitReminderFacts {
  reminderEnabled: boolean;
  submitReminderStartDays: number;
  submitReminderMaxDays: number;
  periodEndYmd: string;
  todayYmd: string;
  timesheetStatus: TimesheetStatus;
}

export type ReminderDecision = { fire: false; reason: string } | { fire: true };

export function decideSubmitReminder(facts: SubmitReminderFacts): ReminderDecision {
  if (!facts.reminderEnabled) return { fire: false, reason: 'DISABLED' };
  if (facts.timesheetStatus !== 'DRAFT' && facts.timesheetStatus !== 'REJECTED') {
    // Only DRAFT + REJECTED need a "please submit" reminder. Once
    // PENDING_* / APPROVED, the ball is out of the employee's court.
    return { fire: false, reason: 'STATUS_NOT_PENDING_SUBMIT' };
  }
  const days = daysBetweenYmd(facts.periodEndYmd, facts.todayYmd);
  if (days < facts.submitReminderStartDays) {
    return { fire: false, reason: 'TOO_EARLY' };
  }
  if (days > facts.submitReminderMaxDays) {
    return { fire: false, reason: 'TOO_LATE' };
  }
  return { fire: true };
}

// ---------------------------------------------------------------------------
// Approval reminder
// ---------------------------------------------------------------------------

export interface ApprovalReminderFacts {
  reminderEnabled: boolean;
  approvalReminderStartDays: number;
  approvalReminderMaxDays: number;
  periodEndYmd: string;
  todayYmd: string;
  timesheetStatus: TimesheetStatus;
}

export type ApprovalReminderDecision =
  { fire: false; reason: string } | { fire: true; targetQueue: 'SUPERVISOR' | 'HR' };

export function decideApprovalReminder(facts: ApprovalReminderFacts): ApprovalReminderDecision {
  if (!facts.reminderEnabled) return { fire: false, reason: 'DISABLED' };
  const targetQueue: 'SUPERVISOR' | 'HR' | null =
    facts.timesheetStatus === 'PENDING_SUPERVISOR'
      ? 'SUPERVISOR'
      : facts.timesheetStatus === 'PENDING_HR'
        ? 'HR'
        : null;
  if (targetQueue === null) {
    return { fire: false, reason: 'STATUS_NOT_PENDING_APPROVAL' };
  }
  const days = daysBetweenYmd(facts.periodEndYmd, facts.todayYmd);
  if (days < facts.approvalReminderStartDays) {
    return { fire: false, reason: 'TOO_EARLY' };
  }
  if (days > facts.approvalReminderMaxDays) {
    return { fire: false, reason: 'TOO_LATE' };
  }
  return { fire: true, targetQueue };
}
