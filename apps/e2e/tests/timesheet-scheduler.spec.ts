async function fireSchedulerTick(): Promise<Array<{
  companyId: string;
  autoGenerated: boolean;
  submitRemindersSent: number;
  approvalRemindersSent: number;
  skipped: boolean;
}>> {
  const { request } = await import('@playwright/test');
  const ctx = await request.newContext({ baseURL: API_URL });
  try {
    const res = await ctx.post(
      '/api/v1/test-support/timesheet-scheduler/tick',
      { data: {} },
    );
    expect(res.ok()).toBeTruthy();
    const body = (await res.json()) as {
      reports: Array<{
        companyId: string;
        autoGenerated: boolean;
        submitRemindersSent: number;
        approvalRemindersSent: number;
        skipped: boolean;
      }>;
    };
    return body.reports;
  } finally {
    await ctx.dispose();
  }
}

test.describe('Timesheet scheduler — Fase 32f', () => {
  test.beforeAll(async () => {
    await prune(SEED_USERS.hr.email);
  });

  test.beforeEach(async () => {
    // Reset config to defaults (both feature flags on) so a previous
    // test can't leave reminders disabled.
    const hr = await login(SEED_USERS.hr.email, SEED_USERS.hr.password);
    await acceptPendingConsent(hr);
    const res = await hr.ctx.put('/api/v1/admin/timesheet/config', {
      headers: { Authorization: `Bearer ${hr.accessToken}` },
      data: {
        periodType: 'MONTHLY',
        autoGenerateEnabled: true,
        reminderEnabled: true,
        submitReminderStartDays: 1,
        submitReminderMaxDays: 30,
        approvalReminderStartDays: 1,
        approvalReminderMaxDays: 30,
      },
    });
    expect(res.status()).toBe(200);
    await hr.ctx.dispose();
  });

  test('reminders fire for DRAFT / PENDING_SUPERVISOR / PENDING_HR, and dedupe on same-day retick', async () => {
    // 1. Generate the current period so we have a materialised
    //    timesheet for every user, then push it >30 days into the past
    //    so `periodEnd` lands before "today" and the reminder decision
    //    window fires. We use 35 days so a MONTHLY period that would
    //    normally end at end-of-month still lands 3-4 days ago.
    const first = await generatePeriod(SEED_USERS.hr.email);
    expect(first.timesheetsGenerated).toBeGreaterThan(0);
    await backdatePeriod(first.periodId, 35);

    // 2. Fetch timesheets so we can force distinct statuses.
    const hr = await login(SEED_USERS.hr.email, SEED_USERS.hr.password);
    await acceptPendingConsent(hr);
    const listRes = await hr.ctx.get(
      `/api/v1/admin/timesheet?periodId=${first.periodId}`,
      { headers: { Authorization: `Bearer ${hr.accessToken}` } },
    );
    expect(listRes.status()).toBe(200);
    const list = (await listRes.json()) as {
      items: Array<{ id: string; user: { email: string } }>;
    };
    expect(list.items.length).toBeGreaterThanOrEqual(3);

    // Force one of each stage so both branches of the decision fire.
    const draft = list.items.find((r) => r.user.email === SEED_USERS.employee.email);
    const pendingSup = list.items.find(
      (r) => r.user.email === SEED_USERS.supervisor.email,
    );
    const pendingHr = list.items.find((r) => r.user.email === SEED_USERS.admin.email);
    expect(draft && pendingSup && pendingHr).toBeTruthy();
    if (!draft || !pendingSup || !pendingHr) throw new Error('seed missing');

    await forceStatus(draft.id, 'DRAFT');
    await forceStatus(pendingSup.id, 'PENDING_SUPERVISOR');
    await forceStatus(pendingHr.id, 'PENDING_HR');

    // 3. First tick — should send at least one submit reminder and at
    //    least one approval reminder.
    const t1 = await fireSchedulerTick();
    const mine = t1.find((r) => !r.skipped);
    expect(mine).toBeDefined();
    expect(mine?.submitRemindersSent ?? 0).toBeGreaterThanOrEqual(1);
    expect(mine?.approvalRemindersSent ?? 0).toBeGreaterThanOrEqual(1);

    // 4. Employee should see a TIMESHEET_SUBMIT_REMINDER in their
    //    notification feed.
    const emp = await login(
      SEED_USERS.employee.email,
      SEED_USERS.employee.password,
    );
    const notif = await emp.ctx.get('/api/v1/notifications?unreadOnly=true', {
      headers: { Authorization: `Bearer ${emp.accessToken}` },
    });
    expect(notif.status()).toBe(200);
    const notifBody = (await notif.json()) as Array<{ type: string }>;
    const hasSubmit = notifBody.some(
      (n) => n.type === 'TIMESHEET_SUBMIT_REMINDER',
    );
    expect(hasSubmit).toBe(true);

    // 5. Second tick same day — must be a no-op (0 new sends).
    const t2 = await fireSchedulerTick();
    const mine2 = t2.find((r) => !r.skipped);
    expect(mine2?.submitRemindersSent ?? 0).toBe(0);
    expect(mine2?.approvalRemindersSent ?? 0).toBe(0);

    await emp.ctx.dispose();
    await hr.ctx.dispose();
  });

  test('reminderEnabled=false disables all nudges', async () => {
    // `prune` deletes the TimesheetConfig too, so we must first wipe
    // the tenant state, then generate (which lazily materialises the
    // config with defaults), and ONLY THEN flip reminderEnabled off.
    // Doing the update before prune would silently be reverted.
    await prune(SEED_USERS.hr.email);
    const first = await generatePeriod(SEED_USERS.hr.email);
    await backdatePeriod(first.periodId, 35);

    const hr = await login(SEED_USERS.hr.email, SEED_USERS.hr.password);
    await acceptPendingConsent(hr);
    const putRes = await hr.ctx.put('/api/v1/admin/timesheet/config', {
      headers: { Authorization: `Bearer ${hr.accessToken}` },
      data: { reminderEnabled: false, autoGenerateEnabled: false },
    });
    expect(putRes.status()).toBe(200);
    await hr.ctx.dispose();

    const t = await fireSchedulerTick();
    const mine = t.find((r) => !r.skipped);
    expect(mine?.submitRemindersSent ?? 0).toBe(0);
    expect(mine?.approvalRemindersSent ?? 0).toBe(0);
  });
});
